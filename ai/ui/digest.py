"""Streamlit section rendering LLM_DAILY_SUMMARIES (Snowflake or local CSV)."""
from __future__ import annotations

import streamlit as st


def _load_digests_discriminatively():
    import os

    if os.getenv("SF_USER"):
        try:
            from ai.data_access.gold_client import connect_sql

            ctx = connect_sql()
            cs = ctx.cursor()
            cs.execute(
                "SELECT * FROM MEOW_DB.ANALYTICS.LLM_DAILY_SUMMARIES ORDER BY digest_date DESC"
            )
            cols = [c[0].lower() for c in cs.description]
            import pandas as pd

            df = pd.DataFrame(cs.fetchall(), columns=cols)
            cs.close()
            ctx.close()
            return df, "snowflake"
        except Exception as exc:
            st.warning(f"Snowflake digest read failed ({exc}); trying local CSV…")
    from ai.config import CONFIG

    if CONFIG.digest_output_csv.exists():
        import pandas as pd

        return pd.read_csv(CONFIG.digest_output_csv), "csv"
    return None, "none"


def render_digest_section() -> None:
    st.subheader("🧠 Daily AI Digests (LLM in-pipeline)")
    st.caption(
        "Generated by the Airflow `llm_digest` task: deterministic health features from the "
        "Gold mart are narrated by the local LLM, then written back to "
        "`ANALYTICS.LLM_DAILY_SUMMARIES` with full provenance (model, prompt hash, tokens)."
    )

    digests, mode = _load_digests_discriminatively()
    if digests is None or digests.empty:
        st.info(
            "No digests yet. Run `python -m ai.pipeline.daily_digest --limit 2` "
            "(mock) or the Airflow task to generate them."
        )
        return

    st.markdown(f"_Source: **{mode}** — {len(digests)} rows._")

    cat_filter = st.multiselect(
        "Filter cats", sorted(digests["cat_name"].unique()),
        default=sorted(digests["cat_name"].unique()),
    )
    filtered = digests[digests["cat_name"].isin(cat_filter)]

    for _, row in filtered.iterrows():
        flags = str(row.get("risk_flags", "") or "")
        emoji = "🚩" if flags and flags.lower() != "none" else "✅"
        with st.container(border=True):
            col_avatar, col_body = st.columns([1, 6])
            with col_avatar:
                st.markdown(f"### {emoji}\n_cat_{row['cat_id'].replace('CAT', '')}_")
            with col_body:
                st.markdown(f"**{row['cat_name']}** — {row.get('digest_date', '')}")
                st.markdown(f"`risk_flags`: {flags if flags else 'none'}")
                st.markdown(f".digest: {row['llm_digest']}")
                meta = (
                    f"model `{row.get('model_name', '?')}` · "
                    f"prompt `{row.get('prompt_hash', '?')}` · "
                    f"tokens {row.get('tokens_used', '?')} · "
                    f"score {row.get('avg_health_score_7d', '?')}/100"
                )
                st.caption(meta)
